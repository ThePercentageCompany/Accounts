import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'package:file_picker/file_picker.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:tpc_invoice/core/network/saas_api.dart';
import 'package:tpc_invoice/core/utils/file_download_stub.dart';
import 'package:tpc_invoice/features/documents/data/shared_record_pdf.dart';

class SavePicker extends FilePicker {
  SavePicker(this.path);
  final String? path;
  Uint8List? received;
  @override
  Future<String?> saveFile(
      {String? dialogTitle,
      String? fileName,
      String? initialDirectory,
      FileType type = FileType.any,
      List<String>? allowedExtensions,
      Uint8List? bytes,
      bool lockParentWindow = false}) async {
    received = bytes;
    return path;
  }
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  final company = 'c' * 43,
      owner = 'o' * 43,
      id = 'r' * 43,
      customer = 'u' * 43;
  for (final section in ['Invoices', 'Quotations']) {
    test(
        '$section PDF generates offline from cached records with bundled fonts',
        () async {
      var online = true, calls = 0;
      final itemTable =
          section == 'Invoices' ? 'InvoiceItems' : 'QuotationItems';
      final parent = section == 'Invoices' ? 'invoiceId' : 'quotationId';
      final data = <String, List<Map<String, dynamic>>>{
        section: [
          {
            'recordId': id,
            'recordVersion': 1,
            'customerId': customer,
            'number': 'DOC-001',
            'status': 'DRAFT',
            'currency': 'AED',
            'issueDate': '2026-10-15',
            'dueDate': '2026-11-15',
            'validUntil': '2026-11-15',
            'subtotal': 100,
            'discount': 0,
            'taxAmount': 5,
            'total': 105
          }
        ],
        'CompanyProfile': [
          {
            'recordId': 'company',
            'recordVersion': 1,
            'name': 'Local Business',
            'address': 'Dubai',
            'currency': 'AED'
          }
        ],
        'Customers': [
          {'recordId': customer, 'name': 'Café & Co'}
        ],
        itemTable: [
          {
            'recordId': 'i' * 43,
            parent: id,
            'lineNumber': 1,
            'description': 'Consulting',
            'quantity': 1,
            'unitPrice': 100,
            'discount': 0,
            'taxRate': 5,
            'taxAmount': 5,
            'lineTotal': 105
          }
        ],
      };
      final api = SaasApi(
          origin: 'https://api.test',
          client: MockClient((request) async {
            calls++;
            if (!online) {
              throw StateError('PDF generation must not request the network');
            }
            expect(request.method, 'GET');
            final table = request.url.pathSegments.last;
            expect(data.containsKey(table), isTrue);
            return http.Response(jsonEncode({'records': data[table]}), 200);
          }));
      addTearDown(api.close);
      api.useVerifiedWorkspace(company, ownerId: owner);
      for (final table in data.keys) {
        await api.records(company, table);
      }
      calls = 0;
      online = false;
      final bytes = await sharedRecordPdf(api, company, section, id);
      expect(ascii.decode(bytes.take(5).toList()), '%PDF-');
      expect(bytes.length, greaterThan(1000));
      expect(calls, 0);
    });
  }

  test('desktop export writes generated bytes to the chosen local file',
      () async {
    final directory = await Directory.systemTemp.createTemp('tpc-local-pdf-');
    final target =
        File('${directory.path}${Platform.pathSeparator}invoice.pdf');
    final picker = SavePicker(target.path);
    FilePicker.platform = picker;
    addTearDown(() async {
      if (await target.exists()) await target.delete();
      await directory.delete();
    });
    final bytes = Uint8List.fromList(ascii.encode('%PDF-local-test'));
    await downloadFilePlatform(bytes,
        filename: 'invoice.pdf', mimeType: 'application/pdf');
    expect(picker.received, bytes);
    expect(await target.readAsBytes(), bytes);
  });
}
